import fs from 'node:fs/promises';
import { inspect } from 'node:util';

const characterMapUrl = new URL('../src/strings/slugify-data/charmap.json', import.meta.url);
const localeMapsUrl = new URL('../src/strings/slugify-data/locales.json', import.meta.url);
const outputUrl = new URL('../src/strings/slugify-data/data.ts', import.meta.url);

const characterMap = JSON.parse(await fs.readFile(characterMapUrl, 'utf8'));
const localeMaps = JSON.parse(await fs.readFile(localeMapsUrl, 'utf8'));
const serialize = (value) => inspect(JSON.stringify(value), { breakLength: Infinity, maxStringLength: Infinity });

const output = `// Generated by scripts/generate-slugify-data.mjs. Do not edit directly.
export const defaultCharacterMap = JSON.parse(
\t${serialize(characterMap)},
) as Readonly<Record<string, string>>;

export const localeMaps = JSON.parse(
\t${serialize(localeMaps)},
) as Readonly<Record<string, Readonly<Record<string, string>>>>;
`;

if (process.argv.includes('--check')) {
	const current = await fs.readFile(outputUrl, 'utf8').catch(() => '');
	if (current !== output) {
		throw new Error('Generated slugify data is stale. Run `pnpm generate:slugify-data`.');
	}
} else {
	await fs.writeFile(outputUrl, output);
}
